function out=intp_4c(in,cfa_idx,awb_gain)
    [height,width,~]=size(in);
    in=uint16(reshape(in'*1023,1,[]));
    [outr,outg,outb]=intp_4c_matlab(in, ...
    cfa_idx, ...
    0, ...
    0, ...
    0, ...
    0, ...
    0, ...
    680, ...
    128, ...
    229, ...
    2, ...
    3, ...
    3, ...
    8, ...
    16, ...
    20, ...
    80, ...
    4, ...
    2, ...
    round(awb_gain(1)*256), ...
    round(awb_gain(2)*256), ...
    round(awb_gain(2)*256), ...
    round(awb_gain(3)*256), ...
    1024, ...
    2048, ...
    8192, ...
    0, ...
    0, ...
    3, ...
    40, ...
    0, ...
    8, ...
    16, ...
    0, ...
    16, ...
    0, ...
    0, ...
    uint8(zeros(1,4)), ...
    uint8(zeros(1,768)), ...
    0, ...
    width, ...
    height);
    
    outr=reshape(double(outr),width,height);
    outr=outr'*awb_gain(1);
    outg=reshape(double(outg),width,height);
    outg=outg'*awb_gain(2);
	outb=reshape(double(outb),width,height);
    outb=outb'*awb_gain(3);

    out=cat(3,outr,outg,outb);
    out=min(max(out,0),1023);
    gamma_x=[0,8,16,24,32,48,64,80,96,112,128,144,160,176,192,224,256,288,320,352,384,416,448,480,512,576,640,704,768,832,896,960,1023];
    gamma_y=[0,32,68,100,128,172,212,244,272,300,328,352,372,392,416,452,488,520,552,580,608,636,664,688,712,760,800,844,880,920,956,992,1023];
    out=interp1(gamma_x,gamma_y,out);
    out=out/1023;
end